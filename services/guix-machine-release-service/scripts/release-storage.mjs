import {isCliEntry} from './cli-entry.mjs';
import {statfsSync, readFileSync, existsSync, mkdirSync, writeFileSync, realpathSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';

export const reserveBytes = 4n * 1024n ** 3n;

export function collectionTarget(filesystem, reserve = reserveBytes) {
  // Guix observes free blocks, including ext4's root reserve. The service user
  // can use only available blocks; collect enough to leave its actual reserve.
  const {bfree,bavail,bsize}=filesystem;
  if ([bfree,bavail,bsize].some(n=>typeof n!=='bigint') || bfree<bavail || bavail<0n || bsize<=0n)
    throw new TypeError('invalid filesystem free/available distinction');
  return reserve+(bfree-bavail)*bsize;
}

// Only Guix decides which immutable objects are unrooted. This operation never
// retires roots, profiles, running builds, application state or release links.
export function guardStorage({readFree, collect, reserve = reserveBytes}) {
  if (typeof reserve !== 'bigint' || reserve <= 0n) throw new TypeError('positive storage reserve required');
  const before = readFree();
  if (typeof before !== 'bigint' || before < 0n) throw new TypeError('invalid available storage');
  if (before < reserve) collect(reserve);
  const after = readFree();
  if (typeof after !== 'bigint' || after < 0n) throw new TypeError('invalid available storage');
  const observation = {kind: 'guix-storage-reserve', beforeBytes: String(before), availableBytes: String(after), reserveBytes: String(reserve), collected: before < reserve, admitted: after >= reserve};
  if (!observation.admitted) {
    const error = new Error(`Storage reserve not met: ${after} available, ${reserve} required; preserve rooted releases and application data`);
    error.observation = observation;
    throw error;
  }
  return observation;
}

export function storageUnits(machine, node, script, configuration) {
  if (!/^[a-z0-9][a-z0-9-]*$/.test(machine)) throw new TypeError('invalid machine unit name');
  const quote = word => {
    if (typeof word !== 'string' || !word.startsWith('/') || /[\r\n\0%]/.test(word)) throw new TypeError('absolute literal unit path required');
    return `"${word.replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"`;
  };
  const service = `${machine}-storage.service`, timer = `${machine}-storage.timer`;
  return {
    [service]: `[Unit]\nDescription=${machine} Guix storage reserve\n[Service]\nType=oneshot\nExecStart=${quote(node)} ${quote(script)} ${quote(configuration)}\nTimeoutStartSec=150\nNice=10\nUMask=0077\n`,
    [timer]: `[Unit]\nDescription=${machine} recurring storage receiving\n[Timer]\nOnBootSec=5min\nOnUnitInactiveSec=15min\nUnit=${service}\n[Install]\nWantedBy=timers.target\n`,
  };
}

// A target builder owns this unpublished directory. The receiving config is
// generated by the authenticated native Scheme constructor immediately before
// this operation; application state and live supervisors are never read here.
if (isCliEntry(import.meta.url) && process.argv[2] === '--fabricate') {
  const [, artifact, ...extra] = process.argv.slice(2);
  if (extra.length || !artifact || realpathSync(artifact) !== artifact) throw new Error('native storage fabrication requires its canonical target output');
  const configuration = join(artifact, '.controller/machine.json');
  const config = JSON.parse(readFileSync(configuration, 'utf8'));
  if ((config.supervisor ?? 'systemd-user') === 'systemd-user') {
    const directory = join(artifact, '.storage-systemd');
    mkdirSync(directory);
    for (const [name, body] of Object.entries(storageUnits(config.name,
      join(artifact, 'bin/node'), join(artifact, '.controller/scripts/release-storage.mjs'), configuration))) {
      writeFileSync(join(directory, name), body, {flag: 'wx', mode: 0o644});
    }
  }
} else if (isCliEntry(import.meta.url)) {
  try {
    const [configuration, locked] = process.argv.slice(2);
    if (!configuration || (locked && locked !== '--locked')) throw new Error('usage: release-storage.mjs MACHINE.json [--locked]');
    const config = JSON.parse(readFileSync(configuration, 'utf8'));
    const lease = join(config.releaseRoot, '.release.lock/lease');
    if (!existsSync(lease)) throw new Error('existing release writer lease required');
    if (!locked) {
      const result = spawnSync('flock', ['--exclusive', '--wait', '5', lease, process.execPath, fileURLToPath(import.meta.url), configuration, '--locked'], {stdio: 'inherit', timeout: 140_000});
      if (result.error) throw result.error;
      process.exit(result.status ?? 1);
    }
    const observation = guardStorage({
      readFree: () => {const s = statfsSync('/gnu/store', {bigint: true}); return s.bavail * s.bsize;},
      collect: reserve => {
        const target=collectionTarget(statfsSync('/gnu/store',{bigint:true}),reserve);
        const result = spawnSync('guix', ['gc', `--free-space=${target}`], {stdio: ['ignore', 'ignore', 'inherit'], timeout: 120_000});
        if (result.error || result.status !== 0) throw result.error ?? new Error(`Guix storage collection failed (${result.status})`);
      },
    });
    console.log(JSON.stringify(observation));
  } catch (error) {
    if (error.observation) console.error(JSON.stringify(error.observation));
    console.error(error.message);
    process.exitCode = 1;
  }
}
